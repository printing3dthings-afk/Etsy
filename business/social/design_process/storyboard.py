"""Shared pieces of every design-process storyboard: parts, cutaway meshes, shot rendering, the
kit's opener and end card, and SCRIPT.md. Each product's own script holds only its story."""
import json
import subprocess
import sys
from pathlib import Path

import trimesh

HERE = Path(__file__).resolve().parent
RES, ENGINE, SAMPLES = [1080, 1080], "EEVEE", 16


def part(path, rgb, keys=None, clip=False):
    d = {"path": str(path), "rgb": rgb, "clip": clip}
    if keys:
        d["keys"] = keys
    return d


def cut(src, dst):
    """The half behind the cut plane y = 0 (y >= 0), capped, as the section renders are."""
    dst = Path(dst)
    if not dst.exists():
        dst.parent.mkdir(parents=True, exist_ok=True)
        trimesh.intersections.slice_mesh_plane(trimesh.load(src), [0, 1, 0], [0, 0, 0], cap=True).export(dst)
    return str(dst)


def render_shots(shots, shots_dir, cam):
    """Render each shot's missing frames. A shot's frames are kept, so changing a shot means a new
    name (a_lift -> a_lift_v2), never deleting frames."""
    for name, s in shots.items():
        d = Path(shots_dir) / name
        have = len(list(d.glob("f_*.png"))) if d.exists() else 0
        if have >= s["frames"]:
            continue
        d.mkdir(parents=True, exist_ok=True)
        s = dict(s, camera=dict(cam, **s["camera"]))     # a shot's own target/radius win
        # a shot may set its own res (template v2 renders 1080 x 1920 portrait)
        spec = dict(s, res=s.get("res", RES), engine=ENGINE, samples=s.get("samples", SAMPLES), out_dir=str(d),
                    frame_from=have + 1)
        sp = Path(shots_dir).parent / f"{name}.json"
        sp.write_text(json.dumps(spec))
        print(f"rendering {name}: frames {have + 1}-{s['frames']}", flush=True)
        r = subprocess.run(["xvfb-run", "-a", "-s", "-screen 0 1280x1024x24", "blender", "-b", "-P",
                            str(HERE / "blender_anim.py"), "--", str(sp)], capture_output=True, text=True)
        if "ANIM_OK" not in r.stdout:
            raise SystemExit(f"{name} failed:\n{r.stdout[-2000:]}\n{r.stderr[-2000:]}")


def kit(out_dir, title):
    k = Path(out_dir) / "kit" / "product"
    if not (k / "product_opener.mp4").exists():
        subprocess.run([sys.executable, str(HERE.parent / "series_motion" / "kit.py"), str(Path(out_dir) / "kit"),
                        "--series", "product", "--only", "opener,endcard", "--title", title,
                        "--kicker", "FROM THE DESIGN FILE", "--chip", "DESIGNED BY US"], check=True)
    return str(k / "product_opener.mp4"), str(k / "product_endcard.mp4")


def write_script(tl, path, title, status, sources):
    rows = []
    for st in tl["steps"]:
        caps = st["captions"] or [(st["start"], "")]
        for k, (t0, text) in enumerate(caps):
            t1 = caps[k + 1][0] if k + 1 < len(caps) else st["end"]
            rows.append(f"| {t0:.1f} | {t1:.1f} | {text} | {st['label']} | {st['chip']} |")
    md = [
        f"# {title}, from the design file: script",
        "",
        "Generated by the storyboard script from the cut's own timeline. The on-screen captions are",
        "the voice-over lines: Benson, read them over the shots, and add music. The video has no audio.",
        "",
        f"- **Length:** {tl['total']:.1f} s. Opener 0 to {tl['opener']:.1f} s; end card from {tl['body_end']:.1f} s.",
        "- **Labels:** every render carries RENDER on screen; Scott's footage and photos carry REAL.",
        f"- **Status:** {status}",
        "",
        "| start | end | line (on screen) | step | tag |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "## Where each claim comes from",
        "",
        *[f"- **{c}:** {s}" for c, s in sources],
        "",
    ]
    Path(path).write_text("\n".join(md))


def save_stills(segments, dst):
    """Keep one still per animated step (its last frame: the state it holds on), beside the video.
    The frames themselves aren't in git, so these are what the media library keeps of the design
    animation. Named by order and step, e.g. 03_inside.jpg."""
    from PIL import Image
    dst = Path(dst)
    dst.mkdir(parents=True, exist_ok=True)
    n = 0
    for seg in segments:
        if seg["kind"] != "frames":
            continue
        fs = sorted(Path(seg["dir"]).glob("f_*.png"))
        if not fs:
            continue
        n += 1
        tag = "cutaway" if "CUTAWAY" in seg.get("chip", "") else "render"
        name = "_".join(w for w in seg.get("label", "").lower().replace(":", "").split())
        Image.open(fs[-1]).convert("RGB").save(dst / f"{n:02d}_{name}_{tag}.jpg", quality=90)
    return n
