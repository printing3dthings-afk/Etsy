#!/usr/bin/env python3
"""Writes love_letter_pmm.scad, the Giant Love Letter's MakerWorld customizer
(2026-11-06), from ../love_letter.scad. Rebuild after any change to it.

Every earlier customizer timed out on MakerWorld. The first one (2026-11-05,
love_letter_customizer.scad, still here) wrote the fixed envelope out as a
1 MB polyhedron; it rendered in 16 s on CGAL here, and PMM gives up at about
10 s. This one is the design itself, made fast where it was slow:
- **Cupid's pocket** was 16.8 of the body's 17.5 s on Manifold: twenty steps
  cut from a 3,752-point outline imported from a DXF. PMM can't import the
  DXF anyway. The outline is embedded, simplified at 0.02 mm and grown
  0.02 mm (412 points), so it is never smaller than the shipped pocket: at
  most 0.08 mm bigger, inside Cupid's 0.3 clearance.
- **Fonts:** Fredoka isn't on PMM, so the name and "To:" drew nothing there.
  They're Nunito ExtraBold, the nearest rounded face PMM has, laid out a
  letter at a time from its own measured advances, as the shipped design is.
- **One file:** the four libraries it includes are inlined.
- **On the plate:** centred on (0, 0), where PMM's preview centres the plate.

The lid and Cupid don't change with the name: they're separate prints, not
in this file, as before.

    python3 build_pmm.py && python3 ../../../../../tools/pmm_check.py love_letter_pmm.scad ...
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

from shapely.geometry import Polygon

HERE = Path(__file__).resolve().parent
LL = HERE.parent
sys.path.insert(0, str(HERE.parents[4] / "tools"))
import pmm_build as pb  # noqa: E402

SRC = LL / "love_letter.scad"
OUT = HERE / "love_letter_pmm.scad"
TOL = 0.02

FONT = "Nunito:style=ExtraBold"
# Nunito ExtraBold's advance per unit size, for name_text.scad's NAME_CHARS,
# measured with OpenSCAD's textmetrics()
NUNITO_ADV = [1.0458, 0.9653, 0.95, 1.075, 0.8403, 0.7917, 1.0306, 1.0833, 0.4125, 0.5167, 0.9556, 0.7958, 1.2167,
              1.0458, 1.1056, 0.9222, 1.1056, 0.9667, 0.8903, 0.8778, 1.0319, 1.0097, 1.5556, 0.9514, 0.8764, 0.8542,
              0.7736, 0.8472, 0.6639, 0.8472, 0.7625, 0.5306, 0.8542, 0.8264, 0.3722, 0.3792, 0.775, 0.4625, 1.2347,
              0.8264, 0.8181, 0.8472, 0.8472, 0.5722, 0.6833, 0.5611, 0.8195, 0.7417, 1.1958, 0.7764, 0.7403, 0.6667,
              0.8333, 0.8333, 0.8333, 0.8333, 0.8333, 0.8333, 0.8333, 0.8333, 0.8333, 0.8333, 0.3875, 0.6111, 0.3556,
              0.3611, 0.3611, 1.0347]

HEADER = '''// Giant Love Letter, the classroom Valentine mailbox: MakerWorld customizer
// (OnBrandCraftz). Generated by customizer/build_pmm.py from love_letter.scad:
// edit that, not this.
//
// This is the envelope's body, with the child's name on the address side.
// The lid and the Cupid charm don't change with the name: print them from
// the model's other files. Print the body standing on its base, supports
// off, 0.2 mm layers.

/* [Personalise] */
// The child's name on the front (it shrinks to fit)
NAME = "OLIVIA";

/* [Colours] */
// The envelope
ENVELOPE_COLOUR = "#F6A6C1"; // color
// The wax seal, stamp heart, postmark and hearts
RED_COLOUR = "#D7263D"; // color
// The stamp and sticker backs
WHITE_COLOUR = "#F4F1EA"; // color
// The name, "To:" and the address line
NAME_COLOUR = "#3B2A3A"; // color

/* [Hidden] */
'''

FOOTER = '''
// ---- what MakerWorld exports: four colours, centred on (0, 0) ----
// (PMM's preview centres the plate on the origin; its export arranges the
// model onto the plate. At (128, 128) it showed off the plate's corner.)
PLATE_CENTRE = [%d, %d];
translate([PLATE_CENTRE[0], PLATE_CENTRE[1], 0]) {
    color(ENVELOPE_COLOUR) body();
    color(RED_COLOUR) body_red();
    color(WHITE_COLOUR) body_white();
    color(NAME_COLOUR) body_dark();
}
''' % pb.PLATE_CENTRE


def pocket_outline():
    """The pocket's 2D outline as the shipped design draws it, simplified."""
    with tempfile.TemporaryDirectory() as td:
        scad, svg = Path(td) / "p.scad", Path(td) / "p.svg"
        scad.write_text('offset(r = 0.3) offset(r = -1.5) offset(r = 1.5) '
                        f'import("{LL / "cupid_white_outline.dxf"}");\n')
        subprocess.run([pb.FAST, "-o", str(svg), str(scad)], check=True, capture_output=True)
        d = re.findall(r' d="([^"]+)"', svg.read_text())
    assert len(d) == 1, f"the pocket outline should be one contour, got {len(d)}"
    num = r"(-?[0-9.]+(?:e-?[0-9]+)?)"
    pts = [(float(a), -float(b)) for a, b in re.findall(num + "," + num, d[0])]   # SVG's y runs down
    p = Polygon(pts)
    q = p.simplify(TOL).buffer(TOL, join_style=2, mitre_limit=2)
    assert q.contains(p.buffer(-1e-6)), "the simplified pocket must hold the shipped one"
    return list(q.exterior.coords)[:-1], p.hausdorff_distance(q), len(pts)


def sub1(pat, rep, s, flags=re.M):
    s, n = re.subn(pat, rep, s, flags=flags)
    assert n == 1, (pat, n)
    return s


def main():
    pts, dev, n0 = pocket_outline()
    s = pb.flatten(SRC)
    s = sub1(r'^NAME = "[^"]*";\n', "", s)
    s = sub1(r'^part = "[^"]*";\n', "", s)
    s = sub1(r'^FONT = "Fredoka:style=SemiBold";', f'FONT = "{FONT}";', s)
    s = sub1(r'^NAME_FONT = "Fredoka:style=SemiBold";', f'NAME_FONT = "{FONT}";', s)
    s = sub1(r'^NAME_ADV = \[[^\]]*\];', f"NAME_ADV = [{', '.join(map(str, NUNITO_ADV))}];", s)
    s = sub1(r'^module cupid_outline\(\) import\("cupid_white_outline.dxf"\);\n', "", s)
    pt_text = ", ".join(f"[{x:.3f}, {y:.3f}]" for x, y in pts)
    s = sub1(r'^module pocket2d\(\) .*cupid_outline\(\);',
             f"// the outline below: the shipped pocket ({n0} points, from his DXF), simplified at\n"
             f"// {TOL} mm and grown {TOL} ({len(pts)} points; at most {dev:.2f} mm bigger)\n"
             f"module pocket2d() polygon(POCKET_PTS);\nPOCKET_PTS = [{pt_text}];", s)
    # the source's outputs, from its first `if (part == ...)` to the end, go
    s = sub1(r'^if\s+\(part == "body"\).*\Z', "", s, flags=re.M | re.S)
    text = HEADER + s.strip() + "\n" + FOOTER
    OUT.write_text(text)
    bad = pb.check_fonts(text) + pb.check_no_imports(text)
    print(f"wrote {OUT.name}: {len(text):,} bytes; pocket {n0} -> {len(pts)} points, at most {dev:.3f} mm out"
          + (f"; PROBLEMS: {bad}" if bad else "; fonts and includes OK"))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
