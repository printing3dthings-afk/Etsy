#!/usr/bin/env python3
"""Write heart_data.scad from layout.json (gear_budget.py): each gear's name, teeth,
centre and phase (the angle of one tooth, with every mesh centred), and the loop's
order round the heart.

    python3 gear_budget.py && python3 make_heart_data.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    d = json.loads((HERE / "layout.json").read_text())
    names = [g["name"] for g in d["gears"]]
    per = max(int(n[5:]) for n in names if n.startswith("right"))
    order = ["top"] + [f"right{i}" for i in range(1, per + 1)] + ["bottom"] + [f"left{i}" for i in range(per, 0, -1)]
    lines = ["// generated by make_heart_data.py from layout.json (gear_budget.py) -- do not edit by hand",
             f"MOD = {d['module']};", "GEARS = ["]
    lines += [f"  [\"{g['name']}\", {g['z']}, [{g['at'][0]:.4f}, {g['at'][1]:.4f}], {g['phase']:.4f}]," for g in d["gears"]]
    lines += ["];", "LOOP = [" + ", ".join(str(names.index(n)) for n in order) + "];"]
    (HERE / "heart_data.scad").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
