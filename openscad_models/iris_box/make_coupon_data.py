#!/usr/bin/env python3
"""Writes coupon_data.scad from the budget (checks/blade.json): the blade's outline in its
own frame, and the region blade 0 sweeps through as the ring turns (the coupon's base
covers it). Re-run after any change to iris_budget.py.

    python3 make_coupon_data.py
"""
import json
import math
from pathlib import Path

import numpy as np
from shapely.geometry import Polygon
from shapely.ops import unary_union

import iris_budget as ib

HERE = Path(__file__).resolve().parent


def main():
    d = json.load(open(HERE / "checks" / "blade.json"))
    blade = Polygon(d["blade"]).simplify(0.05)
    sweep = unary_union([ib.to_world(blade, p, 0) for p in np.linspace(ib.PHI_OPEN, ib.PHI_OPEN + ib.TWIST, 25)])
    sweep = sweep.buffer(2.0).simplify(0.2)
    fmt = lambda poly: "[" + ", ".join(f"[{x:.3f}, {y:.3f}]" for x, y in list(poly.exterior.coords)[:-1]) + "]"
    lines = ["// Generated by make_coupon_data.py from iris_budget.py: edit that, not this.",
             f"RP = {ib.RP}; RD = {ib.RD}; PHI_OPEN = {ib.PHI_OPEN}; TWIST = {ib.TWIST};",
             f"SLOT = [{d['slot'][0]:.3f}, {d['slot'][1]:.3f}];   // drive pin's run from the pivot, mm",
             f"PIN_D = {ib.PIN_D}; R_OUT = {ib.R_OUT};",
             f"BLADE = {fmt(blade)};",
             f"SWEEP = {fmt(sweep)};"]
    (HERE / "coupon_data.scad").write_text("\n".join(lines) + "\n")
    print(f"blade {blade.area:.0f} mm2, {len(blade.exterior.coords)} points; sweep {sweep.area:.0f} mm2")


if __name__ == "__main__":
    main()
