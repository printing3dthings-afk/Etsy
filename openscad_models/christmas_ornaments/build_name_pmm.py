#!/usr/bin/env python3
"""Writes the MakerWorld customizer (PMM) for a flat name ornament (2026-11-18):

    python3 build_name_pmm.py name_ring|name_globe

from <design>/<design>.scad into <design>/pmm/<design>_pmm.scad. Rebuild after
any change to the source. The rules are tools/pmm_build.py's: one file, only
PMM's fonts (both designs already use Lobster and Montserrat), centred on (0, 0)
with the profile's Auto Arrangement on, and fast. Then check it:

    python3 ../../../tools/pmm_check.py <design>_pmm.scad --param NAME \\
        --values Olivia Jessee Mia Christopher MARY-JO Zoë --slice Jessee --report check_pmm.txt
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "tools"))
import pmm_build as pb  # noqa: E402

DESIGNS = {
    "name_ring": dict(
        title="Openwork Name Ornament",
        blurb="A flat open ring, 80 mm across: the name and year raised on their own outline,\n"
              "// a star and pine boughs above, holly below. Print it flat as it lies, supports off.",
        colours=[("FRAME_COLOUR", "#C62F3A", "The ring, the name's outline, the boughs and holly underneath", "frame_marked()"),
                 ("ACCENT_COLOUR", "#F4F1EA", "The name, the year and the tops of the star, boughs and holly", "accent()")]),
    "name_globe": dict(
        title="Snow Globe Name Ornament",
        blurb="A flat snow globe on its base, 62 x 93 mm: a snowy village scene on the glass,\n"
              "// the name and year raised on the base. Print it flat as it lies, supports off.",
        colours=[("FRAME_COLOUR", "#C62F3A", "The globe's rim, the loop and the base", "frame_marked()"),
                 ("GLASS_COLOUR", "#2F4B7C", "The glass behind the scene", "glass()"),
                 ("SNOW_COLOUR", "#F4F1EA", "The scene, the name and the year", "snow()")]),
}


def main(key):
    D = DESIGNS[key]
    src = HERE / key / f"{key}.scad"
    out = HERE / key / "pmm" / f"{key}_pmm.scad"
    out.parent.mkdir(exist_ok=True)
    s = pb.flatten(src)
    # the parameters move to the header, before any module (the Customizer's rule)
    for pat in (r'^NAME = "[^"]*";\n', r'^YEAR = "[^"]*";\n', r'^part = "[^"]*";\n'):
        s, n = re.subn(pat, "", s, flags=re.M)
        assert n == 1, pat
    # the source's own outputs go; the footer is the only one
    s, n = re.subn(r"^(else )?if \(part == .*(\n|$)|^else \{ color\(.*(\n|$)", "", s, flags=re.M)
    assert n == len(D["colours"]) + 2, n   # one per part, union, and the else
    head = (f"// Personalised {D['title']}: MakerWorld customizer (OnBrandCraftz).\n"
            f"// Generated by build_name_pmm.py from {key}.scad: edit that, not this.\n//\n"
            f"// {D['blurb']}\n\n"
            "/* [Personalise] */\n// The name (up to about 11 letters)\nNAME = \"Olivia\";\n"
            "// The year (leave empty for none)\nYEAR = \"2026\";\n\n/* [Colours] */\n")
    for var, hexc, label, _ in D["colours"]:
        head += f"// {label}\n{var} = \"{hexc}\"; // color\n"
    head += "\n/* [Hidden] */\n"
    foot = ("\n// ---- what MakerWorld exports, centred on (0, 0) ----\n"
            "// (PMM's preview centres the plate on the origin; the profile's Auto Arrangement\n"
            "// must be on: tools/pmm_build.py, rule 3.)\n"
            f"PLATE_CENTRE = [{pb.PLATE_CENTRE[0]}, {pb.PLATE_CENTRE[1]}];\n"
            "translate([PLATE_CENTRE[0], PLATE_CENTRE[1], 0]) {\n")
    for var, _, _, mod in D["colours"]:
        foot += f"    color({var}) {mod};\n"
    foot += "}\n"
    text = head + s.strip() + "\n" + foot
    out.write_text(text)
    bad = pb.check_fonts(text) + pb.check_no_imports(text)
    print(f"wrote {out}: {len(text):,} bytes" + (f"; PROBLEMS: {bad}" if bad else "; fonts and includes OK"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
