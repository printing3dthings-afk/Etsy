#!/usr/bin/env python3
"""Writes name_ornament_pmm.scad, the Name Ornament's MakerWorld customizer
(2026-11-06), from ../name_ornament.scad. Rebuild after any change to it.

The first customizer failed both ways on 2026-11-05: the web preview showed an
empty plate, and cloud slicing in Handy failed. Two faults, both fixed here
(tools/pmm_build.py has the rules):
- Dancing Script isn't installed on PMM, so the name drew nothing. The name
  is Lobster now, a connected script PMM has; the year stays Montserrat
  ExtraBold, which PMM has.
- The ornament was centred on (0, 0), the plate's corner in a 3MF: three
  quarters of it hung off the plate. It's centred on the plate now.

    python3 build_pmm.py && python3 check_pmm.py
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[3] / "tools"))
import pmm_build as pb  # noqa: E402

SRC = HERE.parent / "name_ornament.scad"
OUT = HERE / "name_ornament_pmm.scad"

# Lobster's advance per unit size, measured with OpenSCAD's textmetrics(), for
# the name's size rule (PMM's backend may predate textmetrics)
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 -'.!&"
LOBSTER_ADV = [0.9278, 0.8903, 0.6903, 0.9208, 0.6375, 0.6375, 0.8028, 0.9236, 0.5208, 0.7444, 0.8347, 0.5264,
               1.0931, 0.9278, 0.9236, 0.7958, 0.9236, 0.8347, 0.7917, 0.6681, 0.9944, 0.8542, 1.3361, 0.8611,
               0.8611, 0.7528, 0.6486, 0.6167, 0.4736, 0.6611, 0.5083, 0.3708, 0.6667, 0.6292, 0.2903, 0.2958,
               0.6556, 0.2875, 0.9736, 0.6306, 0.6764, 0.65, 0.675, 0.5222, 0.4389, 0.3833, 0.6375, 0.575,
               0.9181, 0.6945, 0.6389, 0.5944, 0.7583, 0.4403, 0.6833, 0.7139, 0.6611, 0.7181, 0.6945, 0.6444,
               0.6931, 0.6792, 0.3014, 0.4028, 0.2722, 0.3653, 0.3569, 0.9472]

HEADER = '''// Personalised Name Ornament: MakerWorld customizer (OnBrandCraftz).
// Generated by pmm/build_pmm.py from name_ornament.scad: edit that, not this.
//
// A domed half-bauble, 80 mm across, with the name and the year inlaid flush
// into its face in a second colour, and a star above. Print it as it lies,
// dome up, supports off, 0.2 mm layers.

/* [Personalise] */
// The name across the dome (up to about 11 letters)
NAME = "Olivia";
// The year under the name
YEAR = "2026";

/* [Colours] */
// The ornament
ORNAMENT_COLOUR = "#C62F3A"; // color
// The name, year, star and maker's mark
NAME_COLOUR = "#F4F1EA"; // color

/* [Hidden] */
'''

FOOTER = '''
// ---- what MakerWorld exports: two colours, centred on a 256 mm plate ----
// (a 3MF's origin is the plate's corner: on (0, 0) the ornament hung off it)
PLATE_CENTRE = [%d, %d];
translate([PLATE_CENTRE[0], PLATE_CENTRE[1], 0]) {
    color(ORNAMENT_COLOUR) body();
    color(NAME_COLOUR) inlay();
}
''' % pb.PLATE_CENTRE


def main():
    s = pb.flatten(SRC)
    # the parameters move to the header, before any module (the Customizer's rule)
    for pat in (r'^NAME = "[^"]*";\n', r'^YEAR = "[^"]*";\n', r'^part = "[^"]*";\n'):
        s, n = re.subn(pat, "", s, flags=re.M)
        assert n == 1, pat
    s, n = re.subn(r'^NAME_FONT = "Dancing Script:style=Bold";', 'NAME_FONT = "Lobster:style=Regular";', s, flags=re.M)
    assert n == 1
    # the name's size: as large as fits 60 across, at most 12 (Lobster stands
    # taller for its size than Dancing Script did), from Lobster's own advances
    size_rule = re.compile(r"^// the name's size:.*?\nNAME_SIZE = [^\n]*\n", re.M | re.S)
    s, n = size_rule.subn(
        "// the name's size: as large as fits 60 mm across, at most 12, from\n"
        "// Lobster's advances (measured with textmetrics; PMM may not have it)\n"
        f'NAME_CHARS = "{CHARS}";\n'
        f"NAME_ADV = [{', '.join(str(a) for a in LOBSTER_ADV)}];\n"
        "function name_adv(c) = let (i = search(c, NAME_CHARS)) len(i) && i[0] != [] ? NAME_ADV[i[0]] : 0.7;\n"
        "function name_w(s, n) = n <= 0 ? 0 : name_w(s, n - 1) + name_adv(s[n - 1]);\n"
        "NAME_SIZE = len(NAME) == 0 ? 12 : min(12, 60 / name_w(NAME, len(NAME)));\n", s)
    assert n == 1
    # the source's own outputs go; the footer is the only one
    s, n = re.subn(r"^if \(part == .*(\n|$)", "", s, flags=re.M)
    assert n == 4, n
    text = HEADER + s.strip() + "\n" + FOOTER
    OUT.write_text(text)
    bad = pb.check_fonts(text) + pb.check_no_imports(text)
    print(f"wrote {OUT.name}: {len(text):,} bytes" + (f"; PROBLEMS: {bad}" if bad else "; fonts and includes OK"))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
